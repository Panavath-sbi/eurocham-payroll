CREATE OR REPLACE VIEW RPT.V_D_LOOKUP 
(
    LOOKUP_TYPE   COMMENT 'ENTITY, FUND or DEPARTMENT',
    CODE, 
    NAME, 
    IS_ACTIVE,
    DISPLAY_ORDER COMMENT 'Sort order (departments); NULL otherwise'
)
COMMENT = 'Values for the app dropdowns: entities, funds and departments.'
AS
SELECT 
    'ENTITY'
    , ENTITY_CODE
    , ENTITY_NAME
    , IS_ACTIVE
    , NULL 
FROM APP.T_D_ENTITY
UNION ALL
SELECT 
    'FUND', 
    FUND_CODE, 
    FUND_NAME, 
    IS_ACTIVE, 
    NULL 
FROM APP.T_D_FUND
UNION ALL
SELECT 
    'DEPARTMENT', 
    DEPARTMENT_CODE, 
    DEPARTMENT_NAME, 
    IS_ACTIVE, 
    DISPLAY_ORDER 
FROM APP.T_D_DEPARTMENT;
