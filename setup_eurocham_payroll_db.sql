-------------------------------------------------------------------------------
-- PAYROLL_DB Environment Setup
-- Run with a role that has CREATE DATABASE, CREATE ROLE, and MANAGE GRANTS
-- (e.g. SYSADMIN + SECURITYADMIN, or ACCOUNTADMIN)
-------------------------------------------------------------------------------

USE ROLE SYSADMIN;

-- 1. Create the database
CREATE DATABASE IF NOT EXISTS EUROCHAM_PAYROLL_DB
    COMMENT = 'Payroll data database for Eurocham payroll processing';

CREATE WAREHOUSE IF NOT EXISTS "EUROCHAM_WH" 
    COMMENT = 'Warehouse for EUROCHAM payroll processeing';

-------------------------------------------------------------------------------
USE ROLE SECURITYADMIN;

-- 2. Create account role (no account-level privileges)
CREATE ROLE IF NOT EXISTS "EUROCHAM_PAYROLL-DBA"
    COMMENT = 'Database administrator role for EUROCHAM_PAYROLL_DB — scoped to database-level operations only, no account privileges';


-- 2. Create account role (no account-level privileges)
CREATE ROLE IF NOT EXISTS "EUROCHAM_PAYROLL-ETL"
    COMMENT = 'Database etl role for EUROCHAM_PAYROLL_DB — scoped to database-level operations only, no account privileges';


-- 3. Grant warehouse usage and database access to the account role
GRANT USAGE ON WAREHOUSE EUROCHAM_WH TO ROLE "EUROCHAM_PAYROLL-DBA";

GRANT USAGE ON DATABASE EUROCHAM_PAYROLL_DB TO ROLE "EUROCHAM_PAYROLL-DBA";
GRANT USAGE ON WAREHOUSE EUROCHAM_WH TO ROLE "EUROCHAM_PAYROLL-ETL";
--GRANT USAGE ON DATABASE EUROCHAM_PAYROLL_DB TO ROLE "EUROCHAM_PAYROLL-ETL";
GRANT MONITOR ON DATABASE EUROCHAM_PAYROLL_DB TO ROLE "EUROCHAM_PAYROLL-DBA";

-------------------------------------------------------------------------------
-- 4. Create DB_READER database role
-------------------------------------------------------------------------------
USE ROLE SYSADMIN;

CREATE DATABASE ROLE IF NOT EXISTS EUROCHAM_PAYROLL_DB.DB_READER
    COMMENT = 'Read-only access to all tables and views in EUROCHAM_PAYROLL_DB';

-- Schema access
GRANT USAGE ON ALL SCHEMAS IN DATABASE EUROCHAM_PAYROLL_DB TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_READER;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE EUROCHAM_PAYROLL_DB TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_READER;

-- Read access on tables and views (current + future)
GRANT SELECT ON ALL TABLES IN DATABASE EUROCHAM_PAYROLL_DB TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_READER;
GRANT SELECT ON FUTURE TABLES IN DATABASE EUROCHAM_PAYROLL_DB TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_READER;
GRANT SELECT ON ALL VIEWS IN DATABASE EUROCHAM_PAYROLL_DB TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_READER;
GRANT SELECT ON FUTURE VIEWS IN DATABASE EUROCHAM_PAYROLL_DB TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_READER;

-------------------------------------------------------------------------------
-- 5. Create DB_WRITER database role (inherits DB_READER)
-------------------------------------------------------------------------------
CREATE DATABASE ROLE IF NOT EXISTS EUROCHAM_PAYROLL_DB.DB_WRITER
    COMMENT = 'Read-write access to EUROCHAM_PAYROLL_DB — inherits DB_READER, adds INSERT/UPDATE/DELETE/TRUNCATE and CREATE TABLE/VIEW';
GRANT DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_READER TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_WRITER;

-- Write access on tables (current + future)
GRANT INSERT, UPDATE, DELETE, TRUNCATE ON ALL TABLES IN DATABASE EUROCHAM_PAYROLL_DB TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_WRITER;
GRANT INSERT, UPDATE, DELETE, TRUNCATE ON FUTURE TABLES IN DATABASE EUROCHAM_PAYROLL_DB TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_WRITER;


-------------------------------------------------------------------------------
-- 6. Create DB_ADMIN database role (inherits DB_WRITER)
-------------------------------------------------------------------------------
CREATE DATABASE ROLE IF NOT EXISTS EUROCHAM_PAYROLL_DB.DB_ADMIN
    COMMENT = 'Full database administration for EUROCHAM_PAYROLL_DB — inherits DB_WRITER, adds CREATE SCHEMA and management of stages, functions, procedures, streams, tasks';
GRANT DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_WRITER TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_ADMIN;

-- Schema management
GRANT CREATE SCHEMA ON DATABASE EUROCHAM_PAYROLL_DB TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_ADMIN;
GRANT MODIFY ON ALL SCHEMAS IN DATABASE EUROCHAM_PAYROLL_DB TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_ADMIN;
GRANT MODIFY ON FUTURE SCHEMAS IN DATABASE EUROCHAM_PAYROLL_DB TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_ADMIN;
GRANT MONITOR ON ALL SCHEMAS IN DATABASE EUROCHAM_PAYROLL_DB TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_ADMIN;
GRANT MONITOR ON FUTURE SCHEMAS IN DATABASE EUROCHAM_PAYROLL_DB TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_ADMIN;

-- Allow creating additional object types within schemas
GRANT CREATE STAGE ON ALL SCHEMAS IN DATABASE EUROCHAM_PAYROLL_DB TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_ADMIN;
GRANT CREATE STAGE ON FUTURE SCHEMAS IN DATABASE EUROCHAM_PAYROLL_DB TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_ADMIN;
GRANT CREATE FILE FORMAT ON ALL SCHEMAS IN DATABASE EUROCHAM_PAYROLL_DB TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_ADMIN;
GRANT CREATE FILE FORMAT ON FUTURE SCHEMAS IN DATABASE EUROCHAM_PAYROLL_DB TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_ADMIN;
GRANT CREATE SEQUENCE ON ALL SCHEMAS IN DATABASE EUROCHAM_PAYROLL_DB TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_ADMIN;
GRANT CREATE SEQUENCE ON FUTURE SCHEMAS IN DATABASE EUROCHAM_PAYROLL_DB TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_ADMIN;
GRANT CREATE FUNCTION ON ALL SCHEMAS IN DATABASE EUROCHAM_PAYROLL_DB TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_ADMIN;
GRANT CREATE FUNCTION ON FUTURE SCHEMAS IN DATABASE EUROCHAM_PAYROLL_DB TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_ADMIN;
GRANT CREATE PROCEDURE ON ALL SCHEMAS IN DATABASE EUROCHAM_PAYROLL_DB TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_ADMIN;
GRANT CREATE PROCEDURE ON FUTURE SCHEMAS IN DATABASE EUROCHAM_PAYROLL_DB TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_ADMIN;
GRANT CREATE STREAM ON ALL SCHEMAS IN DATABASE EUROCHAM_PAYROLL_DB TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_ADMIN;
GRANT CREATE STREAM ON FUTURE SCHEMAS IN DATABASE EUROCHAM_PAYROLL_DB TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_ADMIN;
GRANT CREATE TASK ON ALL SCHEMAS IN DATABASE EUROCHAM_PAYROLL_DB TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_ADMIN;
GRANT CREATE TASK ON FUTURE SCHEMAS IN DATABASE EUROCHAM_PAYROLL_DB TO DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_ADMIN;

-------------------------------------------------------------------------------
-- 7. Wire the hierarchy: DB_ADMIN → account role
-------------------------------------------------------------------------------
USE ROLE SECURITYADMIN;

GRANT DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_ADMIN TO ROLE "EUROCHAM_PAYROLL-DBA";
GRANT DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_WRITER TO ROLE "EUROCHAM_PAYROLL-ETL";

-------------------------------------------------------------------------------
-- 8. Session policy: disable secondary roles for payroll users
-------------------------------------------------------------------------------

CREATE OR REPLACE SESSION POLICY EUROCHAM_PAYROLL_DB.PUBLIC.PAYROLL_SESSION_POLICY
    SESSION_IDLE_TIMEOUT_MINS    = 60
    SESSION_UI_IDLE_TIMEOUT_MINS = 30
    ALLOWED_SECONDARY_ROLES      = ()
    COMMENT = 'Disables secondary roles for payroll users — ensures visibility is limited to EUROCHAM_PAYROLL_DB only';

ALTER SESSION POLICY EUROCHAM_PAYROLL_DB.PUBLIC.PAYROLL_SESSION_POLICY SET TAG
    SNOWFLAKE.TAGS.PROJECT = 'Eurocham';

GRANT OWNERSHIP ON SESSION POLICY EUROCHAM_PAYROLL_DB.PUBLIC.PAYROLL_SESSION_POLICY TO ROLE "EUROCHAM_PAYROLL-DBA";

