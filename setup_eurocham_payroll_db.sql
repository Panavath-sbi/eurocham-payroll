GRANT DATABASE ROLE EUROCHAM_PAYROLL_DB.DB_WRITER TO ROLE "EUROCHAM_PAYROLL-ETL";

-------------------------------------------------------------------------------
-- 10. Session policy: disable secondary roles for payroll users
-------------------------------------------------------------------------------
USE ROLE "EUROCHAM_PAYROLL-DBA";

CREATE OR REPLACE SESSION POLICY EUROCHAM_PAYROLL_DB.PUBLIC.PAYROLL_SESSION_POLICY
    SESSION_IDLE_TIMEOUT_MINS    = 60
    SESSION_UI_IDLE_TIMEOUT_MINS = 30
    ALLOWED_SECONDARY_ROLES      = ()
    COMMENT = 'Disables secondary roles for payroll users — ensures visibility is limited to EUROCHAM_PAYROLL_DB only';

