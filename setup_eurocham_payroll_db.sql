--     (the Object ID of the Enterprise Application / service principal)
USE ROLE USERADMIN;
CREATE USER IF NOT EXISTS EUROCHAM_PAYROLL_SERVICE_USER
    LOGIN_NAME    = '9491c2f8-093b-4fa9-8532-f99f00e8ea27'
    DISPLAY_NAME  = 'Eurocham Payroll Entra Service Principal'
    DEFAULT_ROLE  = "EUROCHAM_PAYROLL-ETL"
    DEFAULT_WAREHOUSE  = "EUROCHAM_WH"
    DEFAULT_NAMESPACE  = "EUROCHAM_PAYROLL_DB.APP"
    TYPE          = SERVICE
    COMMENT       = 'Service user for programmatic Entra ID OAuth access to Eurocham payroll data';

USE ROLE "SYSADMIN";
