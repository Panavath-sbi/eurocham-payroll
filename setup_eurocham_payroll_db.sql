-------------------------------------------------------------------------------
-- 13. Diagnostics: recent queries by the service user (last 24h)
-------------------------------------------------------------------------------
SELECT
    QUERY_TEXT,
    ERROR_CODE,
    ERROR_MESSAGE,
    EXECUTION_STATUS,
    START_TIME,
    WAREHOUSE_NAME,
    ROLE_NAME
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
WHERE USER_NAME = 'EUROCHAM_PAYROLL_SERVICE_USER'
  AND START_TIME >= DATEADD('hour', -24, CURRENT_TIMESTAMP())
ORDER BY START_TIME DESC
LIMIT 30;