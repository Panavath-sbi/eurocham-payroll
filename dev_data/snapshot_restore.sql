/* =====================================================================================
   DEV DATA - RESTORE THE SNAPSHOT SAVED BY snapshot_save.sql
   Development / test only. Puts every APP table back exactly as it was when the
   snapshot was saved; everything written since (e.g. the Excel history load) is gone.
   =====================================================================================

   HISTORY
   -------
   2026-10-19  Initial version: INSERT OVERWRITE of the 20 APP tables from APP.BAK_<table>,
               in one transaction.

   Only table contents are replaced: procedures, views and grants stay as they are.
   All or nothing: if one table fails (e.g. a BAK_ table is missing), nothing is changed.
   The snapshot is kept, so this can be run again; remove it with snapshot_drop.sql.
   Run in Snowsight with Run All, in the same database as snapshot_save.sql.
   ===================================================================================== */

